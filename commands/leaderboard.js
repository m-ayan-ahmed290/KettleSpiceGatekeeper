const { SlashCommandBuilder } = require("@discordjs/builders");
const {
  MessageEmbed,
  Permissions,
  MessageActionRow,
  MessageButton,
} = require("discord.js");
const creditSchema = require("../schemas/credits");
const legacyCreditSchema = require("../schemas/legacyCredits");
const shipSchema = require("../schemas/shipSchema");
const { emoji } = require("../data/emojis.json");

const ITEMS_PER_PAGE = 10;
const MAX_SHIPS = 50;
const MAX_CREDITS = 50;

module.exports = {
  data: new SlashCommandBuilder()
    .setName("leaderboard")
    .setDescription("Check leaderboard for various actions.")
    .addSubcommand((subcommand) =>
      subcommand
        .setName("credits")
        .setDescription("Check the credits leaderboard."),
    )
    .addSubcommand((subcommand) =>
      subcommand
        .setName("ships")
        .setDescription("Check the ships leaderboard."),
    )
    .addSubcommand((subcommand) =>
      subcommand
        .setName("legacy-credits")
        .setDescription("Check the archived (pre-rework) credits leaderboard."),
    )
    .setDefaultMemberPermissions(Permissions.FLAGS.MANAGE_MESSAGES),

  async execute(interaction) {
    const subcmd = interaction.options.getSubcommand();

    try {
      if (subcmd === "credits") {
        await this.handleCreditsLeaderboard(
          interaction,
          creditSchema,
          "Credits Leaderboard",
          "credits",
        );
      } else if (subcmd === "legacy-credits") {
        await this.handleCreditsLeaderboard(
          interaction,
          legacyCreditSchema,
          "Legacy Credits Leaderboard",
          "legacy-credits",
        );
      } else if (subcmd === "ships") {
        await this.handleShipsLeaderboard(interaction);
      }
    } catch (error) {
      console.error(`Error in leaderboard command (${subcmd}):`, error);

      const errorMessage = {
        content: `${emoji.failure} There was an error fetching the leaderboard.`,
        ephemeral: true,
      };

      if (interaction.replied || interaction.deferred) {
        await interaction.followUp(errorMessage);
      } else {
        await interaction.reply(errorMessage);
      }
    }
  },

  async handleCreditsLeaderboard(interaction, model, title, type) {
    const topUsers = await model
      .find()
      .sort({ Credits: -1 })
      .limit(MAX_CREDITS)
      .lean();

    if (!topUsers.length) {
      return interaction.reply({
        content: `${emoji.failure} No users found in the database!`,
        ephemeral: true,
      });
    }

    const totalPages = Math.ceil(topUsers.length / ITEMS_PER_PAGE);
    const currentPage = 1;

    const embed = this.createCreditsEmbed(
      topUsers,
      currentPage,
      totalPages,
      interaction,
      title,
    );
    const components = this.createNavigationButtons(
      currentPage,
      totalPages,
      type,
    );

    const response = await interaction.reply({
      embeds: [embed],
      components: components.length > 0 ? components : [],
      fetchReply: true,
    });

    if (totalPages > 1) {
      this.setupNavigationCollector(
        response,
        topUsers,
        type,
        interaction,
        title,
      );
    }
  },

  async handleShipsLeaderboard(interaction) {
    const topShips = await shipSchema
      .find()
      .sort({ ShipStr: -1 })
      .limit(MAX_SHIPS)
      .lean();

    if (!topShips.length) {
      return interaction.reply({
        content: `${emoji.failure} No ships found in the database!`,
        ephemeral: true,
      });
    }

    const totalPages = Math.ceil(topShips.length / ITEMS_PER_PAGE);
    const currentPage = 1;

    const embed = this.createShipsEmbed(
      topShips,
      currentPage,
      totalPages,
      interaction,
    );
    const components = this.createNavigationButtons(
      currentPage,
      totalPages,
      "ships",
    );

    const response = await interaction.reply({
      embeds: [embed],
      components: components.length > 0 ? components : [],
      fetchReply: true,
    });

    if (totalPages > 1) {
      this.setupNavigationCollector(response, topShips, "ships", interaction);
    }
  },

  createCreditsEmbed(
    users,
    page,
    totalPages,
    interaction,
    title = "Credits Leaderboard",
  ) {
    const embed = new MessageEmbed()
      .setTitle(title)
      .setColor("#FFD700") // Gold color in hex
      .setThumbnail(interaction.guild.iconURL({ dynamic: true }))
      .setFooter({
        text: `Generated by: ${interaction.user.username} • Page ${page}/${totalPages}`,
        iconURL: interaction.user.displayAvatarURL({ dynamic: true }),
      })
      .setTimestamp();

    const startIndex = (page - 1) * ITEMS_PER_PAGE;
    const endIndex = Math.min(startIndex + ITEMS_PER_PAGE, users.length);
    const pageUsers = users.slice(startIndex, endIndex);

    pageUsers.forEach((user, index) => {
      const position = startIndex + index + 1;
      const medal = this.getMedal(position);

      embed.addFields({
        name: `${medal} #${position} ${user.Username}`,
        value: `${emoji.credits} **${user.Credits.toLocaleString()}** credits`,
        inline: false,
      });
    });

    return embed;
  },

  createShipsEmbed(ships, page, totalPages, interaction) {
    const embed = new MessageEmbed()
      .setTitle(`Ships Leaderboard`)
      .setColor("#FFC0CB") // Pink color in hex
      .setThumbnail(interaction.guild.iconURL({ dynamic: true }))
      .setFooter({
        text: `Generated by: ${interaction.user.username} • Page ${page}/${totalPages}`,
        iconURL: interaction.user.displayAvatarURL({ dynamic: true }),
      })
      .setTimestamp();

    const startIndex = (page - 1) * ITEMS_PER_PAGE;
    const endIndex = Math.min(startIndex + ITEMS_PER_PAGE, ships.length);
    const pageShips = ships.slice(startIndex, endIndex);

    pageShips.forEach((ship, index) => {
      const position = startIndex + index + 1;
      const medal = this.getMedal(position);
      const hearts = this.getHearts(ship.ShipStr);

      embed.addFields({
        name: `${medal} #${position} ${ship.ShipName}`,
        value: `${hearts} **${ship.ShipStr}%** compatibility`,
        inline: false,
      });
    });

    return embed;
  },

  getMedal(position) {
    switch (position) {
      case 1:
        return "🥇";
      case 2:
        return "🥈";
      case 3:
        return "🥉";
      default:
        return "🏅";
    }
  },

  getHearts(percentage) {
    if (percentage >= 90) return "💖💖💖";
    if (percentage >= 70) return "💖💖";
    if (percentage >= 50) return "💖";
    if (percentage >= 30) return "💔";
    return "💔💔";
  },

  createNavigationButtons(currentPage, totalPages, type) {
    if (totalPages <= 1) return [];

    const row = new MessageActionRow();

    // Previous button
    row.addComponents(
      new MessageButton()
        .setCustomId(`${type}_prev_${currentPage}`)
        .setLabel("◀ Previous")
        .setStyle("SECONDARY")
        .setDisabled(currentPage === 1),
    );

    // Page indicator
    row.addComponents(
      new MessageButton()
        .setCustomId(`${type}_page_${currentPage}`)
        .setLabel(`${currentPage}/${totalPages}`)
        .setStyle("PRIMARY")
        .setDisabled(true),
    );

    // Next button
    row.addComponents(
      new MessageButton()
        .setCustomId(`${type}_next_${currentPage}`)
        .setLabel("Next ▶")
        .setStyle("SECONDARY")
        .setDisabled(currentPage === totalPages),
    );

    return [row];
  },

  setupNavigationCollector(message, data, type, originalInteraction, title) {
    const filter = (buttonInteraction) => {
      return (
        buttonInteraction.customId.startsWith(type) &&
        buttonInteraction.user.id === originalInteraction.user.id
      );
    };

    const collector = message.createMessageComponentCollector({
      filter,
      time: 300000, // 5 minutes
    });

    collector.on("collect", async (buttonInteraction) => {
      try {
        const [, action, currentPageStr] =
          buttonInteraction.customId.split("_");
        let currentPage = parseInt(currentPageStr);
        const totalPages = Math.ceil(data.length / ITEMS_PER_PAGE);

        if (action === "prev" && currentPage > 1) {
          currentPage--;
        } else if (action === "next" && currentPage < totalPages) {
          currentPage++;
        } else {
          // Invalid action, just acknowledge
          await buttonInteraction.deferUpdate();
          return;
        }

        let embed;
        if (type === "credits" || type === "legacy-credits") {
          embed = this.createCreditsEmbed(
            data,
            currentPage,
            totalPages,
            originalInteraction,
            title,
          );
        } else if (type === "ships") {
          embed = this.createShipsEmbed(
            data,
            currentPage,
            totalPages,
            originalInteraction,
          );
        }

        const components = this.createNavigationButtons(
          currentPage,
          totalPages,
          type,
        );

        await buttonInteraction.update({
          embeds: [embed],
          components: components.length > 0 ? components : [],
        });
      } catch (error) {
        console.error("Error handling navigation button:", error);
        if (!buttonInteraction.replied && !buttonInteraction.deferred) {
          await buttonInteraction.deferUpdate();
        }
      }
    });

    collector.on("end", async () => {
      try {
        // Disable all buttons when collector expires
        const disabledComponents = message.components.map((row) => {
          const newRow = new MessageActionRow();
          row.components.forEach((component) => {
            newRow.addComponents(
              new MessageButton()
                .setCustomId(component.customId)
                .setLabel(component.label)
                .setStyle(component.style)
                .setDisabled(true),
            );
          });
          return newRow;
        });

        await message.edit({
          components: disabledComponents,
        });
      } catch (error) {
        console.error("Error disabling buttons:", error);
      }
    });
  },
};
